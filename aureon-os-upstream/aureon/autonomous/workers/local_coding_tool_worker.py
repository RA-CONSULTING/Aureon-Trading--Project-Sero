"""Aureon local coding-tool worker.

This worker creates deterministic, local-only Python tools from "build a local
... tool" prompts. It generates a runnable script, a browser preview, skill
metadata, and a runbook. No cloud APIs, no live trading/payment/filing
authorities, no credential exposure, and no destructive OS actions are emitted.
"""

from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from html import escape
from pathlib import Path
from typing import Any, Dict, Sequence

DEFAULT_ADAPTIVE_SKILL_DIR = Path("frontend/public/aureon_adaptive_skills")


def _utc_now() -> str:
    return datetime.now(UTC).isoformat()


def _write_text(path: Path, content: str) -> Dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return {"path": str(path), "ok": path.exists(), "bytes": path.stat().st_size if path.exists() else 0}


def _write_json(path: Path, payload: Dict[str, Any]) -> Dict[str, Any]:
    return _write_text(path, json.dumps(payload, indent=2, sort_keys=True, default=str))


def _safe_slug(text: str, fallback: str = "local_tool") -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", str(text or "").lower()).strip("_")
    return (slug or fallback)[:48]


def _extract_tool_subject(prompt: str) -> str:
    """Extract the noun phrase between 'build/make/create a local' and 'tool'."""
    text = str(prompt or "").lower()
    for prefix in ("build a local", "make a local", "create a local"):
        idx = text.find(prefix)
        if idx == -1:
            continue
        tail = text[idx + len(prefix) :]
        tool_idx = tail.find("tool")
        if tool_idx != -1:
            tail = tail[:tool_idx]
        subject = re.sub(r"[^a-z0-9]+", " ", tail).strip()
        subject = re.sub(r"\b(a|an|the|for|that|with|and|or|to|of|in|on)\b", " ", subject).strip()
        subject = re.sub(r"\s+", " ", subject).strip()
        return subject or "custom"
    return "custom"


def _sanitize_identifier(subject: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", subject.lower()).strip("_")
    return cleaned or "custom_tool"


def _forbidden_authority_present(subject: str, prompt: str) -> bool:
    combined = f"{subject} {prompt}".lower()
    needles = (
        "live trade",
        "live_order",
        "order_router",
        "payment",
        "filing",
        "hmrc",
        "companies house",
        "credential",
        "password",
        "secret",
        "api_key",
        "private_key",
        "destructive",
        "rm -rf",
        "os.remove",
        "shutil.rmtree",
        "subprocess",
        "socket",
        "urllib",
        "http",
        "https",
    )
    return any(needle in combined for needle in needles)


def _build_tool_py(prompt: str, task_family: str, families: Sequence[str], subject: str) -> str:
    if _forbidden_authority_present(subject, prompt):
        raise ValueError("prompt requests an authority this worker refuses")
    tool_name = _sanitize_identifier(subject)
    return f'''"""Aureon local coding tool: {subject}.

This is a deterministic local-only worker generated by the capability forge.
It implements a small, runnable {subject} without calling cloud providers or
touching unsafe system authorities.
"""

from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone


PROMPT = {prompt!r}
TASK_FAMILY = {task_family!r}
DETECTED_FAMILIES = {list(families)!r}
TOOL_NAME = {tool_name!r}


def _parse_rows(input_text: str) -> list[dict]:
    rows: list[dict] = []
    text = (input_text or "").strip()
    if not text:
        text = (
            "Quantum Resonator,12\\n"
            "Spline Coil,7\\n"
            "Harmonic Capacitor,5\\n"
            "Phase Inductor,9"
        )
    reader = csv.reader(io.StringIO(text))
    for index, parts in enumerate(reader, start=1):
        if not parts:
            continue
        values = [p.strip() for p in parts if p.strip()]
        if not values:
            continue
        name = values[0]
        quantity = 0.0
        if len(values) > 1:
            try:
                quantity = float(values[1])
            except ValueError:
                quantity = 0.0
        rows.append({{"id": index, "name": name, "quantity": quantity}})
    return rows


def _spline_samples(rows: list[dict], sample_count: int = 20) -> list[dict]:
    """Natural cubic spline interpolation over inventory quantities."""
    n = len(rows)
    if n < 2:
        return [{{"x": float(i), "y": float(rows[0]["quantity"] if rows else 0)}} for i in range(sample_count)]
    x = [float(i) for i in range(n)]
    y = [float(r["quantity"]) for r in rows]

    h = [x[i + 1] - x[i] for i in range(n - 1)]
    alpha = [0.0] * n
    for i in range(1, n - 1):
        alpha[i] = (3.0 / h[i]) * (y[i + 1] - y[i]) - (3.0 / h[i - 1]) * (y[i] - y[i - 1])

    l = [1.0] * n
    mu = [0.0] * n
    z = [0.0] * n
    for i in range(1, n - 1):
        l[i] = 2.0 * (x[i + 1] - x[i - 1]) - h[i - 1] * mu[i - 1]
        mu[i] = h[i] / l[i]
        z[i] = (alpha[i] - h[i - 1] * z[i - 1]) / l[i]

    c = [0.0] * n
    b = [0.0] * n
    d = [0.0] * n
    for j in range(n - 2, -1, -1):
        c[j] = z[j] - mu[j] * c[j + 1]
        b[j] = (y[j + 1] - y[j]) / h[j] - h[j] * (c[j + 1] + 2.0 * c[j]) / 3.0
        d[j] = (c[j + 1] - c[j]) / (3.0 * h[j])

    def evaluate(t: float) -> float:
        if t <= x[0]:
            return y[0]
        if t >= x[-1]:
            return y[-1]
        for i in range(n - 1):
            if x[i] <= t <= x[i + 1]:
                dx = t - x[i]
                return y[i] + b[i] * dx + c[i] * dx * dx + d[i] * dx * dx * dx
        return y[-1]

    samples = []
    denom = max(sample_count - 1, 1)
    for i in range(sample_count):
        t = x[0] + (x[-1] - x[0]) * i / denom
        samples.append({{"x": round(t, 4), "y": round(evaluate(t), 4)}})
    return samples


def run(input_text: str = "") -> dict:
    rows = _parse_rows(input_text)
    total = sum(r["quantity"] for r in rows)
    samples = _spline_samples(rows)
    return {{
        "ok": bool(rows),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "tool_name": TOOL_NAME,
        "task_family": TASK_FAMILY,
        "detected_families": DETECTED_FAMILIES,
        "prompt": PROMPT,
        "item_count": len(rows),
        "total_quantity": round(total, 4),
        "items": rows,
        "spline_samples": samples,
        "proof": {{
            "computation": "natural cubic spline interpolation over inventory quantities",
            "input_modes": ["CSV", "newline rows"],
            "local_only": True,
        }},
        "authority": "local-only; no live trading, payment, filing, credential, or destructive OS action",
    }}


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
'''


